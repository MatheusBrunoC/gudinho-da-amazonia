BEGIN;

CREATE TABLE IF NOT EXISTS public.jogadores (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    apelido VARCHAR(30) NOT NULL,
    criado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    nome_usuario VARCHAR(30),
    senha_hash VARCHAR(255),

    CONSTRAINT chk_jogadores_id
        CHECK (id > 0),

    CONSTRAINT chk_jogadores_apelido
        CHECK (CHAR_LENGTH(TRIM(apelido)) BETWEEN 1 AND 30),

    CONSTRAINT chk_jogadores_credenciais
        CHECK (
            (nome_usuario IS NULL AND senha_hash IS NULL)
            OR
            (nome_usuario IS NOT NULL AND senha_hash IS NOT NULL)
        )
);

CREATE UNIQUE INDEX IF NOT EXISTS uq_jogadores_nome_usuario
    ON public.jogadores (LOWER(nome_usuario));


CREATE TABLE IF NOT EXISTS public.historico_treinos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    identificador UUID NOT NULL,
    jogador_id BIGINT NOT NULL,
    pontos_jogador INTEGER NOT NULL,
    pontos_computador INTEGER NOT NULL,
    criado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT chk_historico_treinos_id
        CHECK (id > 0),

    CONSTRAINT uq_historico_treinos_identificador
        UNIQUE (identificador),

    CONSTRAINT fk_historico_treinos_jogador
        FOREIGN KEY (jogador_id)
        REFERENCES public.jogadores (id),

    CONSTRAINT chk_historico_pontos_jogador
        CHECK (pontos_jogador >= 0),

    CONSTRAINT chk_historico_pontos_computador
        CHECK (pontos_computador >= 0)
);

CREATE INDEX IF NOT EXISTS idx_historico_treinos_jogador_data
    ON public.historico_treinos (
        jogador_id,
        criado_em DESC,
        id DESC
    );

COMMIT;